/* ============================================================
   dp-fashion.js — دانش واقعیِ دنیای مد
   ------------------------------------------------------------
   این فایل «مغز» پیشنهاد دیجی AI است. چیزی که اینجا نوشته
   شده حدس و سلیقه‌ی شخصی نیست؛ قاعده‌هایی است که در دنیای
   واقعیِ استایلینگ سال‌هاست به کار می‌رود:

     • قاعده‌ی ۶۰-۳۰-۱۰   — تقسیم رنگ در یک تیپ
     • تحلیل رنگ فصلی      — گرم/سرد، روشن/عمیق
     • نردبان رسمیت        — چهار پله‌ی جهانی پوشش
     • تعادل حجم           — گشاد با جذب
     • وزن پارچه و فصل     — کتان تابستان، پشم زمستان
     • کپسول ورزوب         — چند قطعه چند تیپ می‌سازد
     • قاعده‌ی یک کانون    — فقط یک قطعه فریاد بزند

   هیچ وابستگی بیرونی ندارد. فقط جاوااسکریپت ساده.
   ============================================================ */
(function () {
  'use strict';

  /* ============================================================
     ۱. مناسبت‌های واقعی — «کجا می‌شود این را پوشید؟»
     ------------------------------------------------------------
     در صنعت مد به این «Dress Code» می‌گویند. مشتری معمولاً
     برای یک مناسبت خرید می‌کند، نه برای یک دسته‌بندی.
     ============================================================ */
  var OCCASION = {
    0: { key: 'home',    name: 'خانه و استراحت',  hint: 'راحتی مطلق' },
    1: { key: 'sport',   name: 'ورزش و پیاده‌روی', hint: 'تحرک آزاد' },
    2: { key: 'daily',   name: 'روزمره و بیرون',   hint: 'شیک اما راحت' },
    3: { key: 'smart',   name: 'اداری و دورهمی',   hint: 'مرتب و آبرومند' },
    4: { key: 'formal',  name: 'رسمی و کاری',      hint: 'جدی و حرفه‌ای' },
    5: { key: 'party',   name: 'مجلسی و شب',       hint: 'خاص و درخشان' },
  };

  function occasionOf(level) {
    /* ⚠️ `Number(level) || 2` غلط بود: عدد صفر در جاوااسکریپت
       «نادرست» شمرده می‌شود، پس سطح ۰ (خانه) به ۲ می‌افتاد.
       باید صریح بررسی شود که عدد معتبر است یا نه. */
    var v = Number(level);
    if (!Number.isFinite(v)) v = 2;
    var n = Math.max(0, Math.min(5, Math.round(v)));
    return OCCASION[n];
  }

  /* ============================================================
     ۲. قاعده‌ی ۶۰-۳۰-۱۰
     ------------------------------------------------------------
     در طراحی داخلی و مد یکی است: ۶۰٪ رنگ اصلی (معمولاً
     پایین‌تنه یا رویه)، ۳۰٪ رنگ دوم (بالاتنه)، ۱۰٪ رنگ
     تأکید (کیف، کفش، اکسسوری). تیپی که این نسبت را رعایت
     کند، «چیده‌شده» به نظر می‌رسد نه شلوغ.
     ============================================================ */
  var SHARE = {
    bottom: 60, full: 60, outer: 60,
    top: 30, modest: 30,
    shoes: 10, bag: 10, accessory: 10,
    under: 0, home: 0,
  };

  function shareOf(slot) { return SHARE[slot] != null ? SHARE[slot] : 20; }

  /* بررسی می‌کند تیپ ساخته‌شده تا چه اندازه به ۶۰-۳۰-۱۰ نزدیک است */
  function balanceReport(slots) {
    var sum = 0, has60 = false, has10 = false;
    slots.forEach(function (s) {
      var v = shareOf(s);
      sum += v;
      if (v >= 60) has60 = true;
      if (v <= 10 && v > 0) has10 = true;
    });
    if (has60 && has10 && sum >= 90 && sum <= 115) {
      return { ok: true, text: 'نسبت رنگ ۶۰-۳۰-۱۰ رعایت شده — تیپ چیده‌شده به نظر می‌رسد' };
    }
    if (!has10) {
      return { ok: false, text: 'یک قطعه‌ی کوچک تأکیدی (کیف یا کفش) این تیپ را کامل‌تر می‌کند' };
    }
    if (!has60) {
      return { ok: false, text: 'یک قطعه‌ی بزرگ پایه (شلوار یا رویه) به این ست وزن می‌دهد' };
    }
    return { ok: true, text: 'ترکیب متعادلی از قطعه‌های بزرگ و کوچک' };
  }

  /* ============================================================
     ۳. کانون تیپ — قاعده‌ی «فقط یکی فریاد بزند»
     ------------------------------------------------------------
     یک تیپ حرفه‌ای فقط یک نقطه‌ی توجه دارد: یا رنگ تند، یا
     طرح شلوغ، یا فرم غیرمعمول. دو تا که شد، چشم گیج می‌شود.
     ============================================================ */
  var LOUD_COLORS = {
    red: 1, orange: 1, yellow: 1, pink: 1, purple: 1, turquoise: 1, green: 1, blue: 0.6,
  };

  function loudnessOf(p, hueKey) {
    var n = 0;

    /* ---------- طرح ----------
       دانشنامه شلوغی هر طرح را دقیق می‌داند: «خال ریز» با
       «چهارخانه‌ی اسکاتلندی» یکی نیست. */
    if (window.DPPalette) {
      var pat = DPPalette.patternOf(p.pattern);
      n += pat.busy * 0.7;
    } else {
      var q = String(p.pattern || 'plain');
      if (q && q !== 'plain' && q !== 'none') n += 1;
    }

    /* ---------- رنگ ----------
       شدت واقعی رنگ، نه فهرست دستی. رنگ پرشدت و روشن
       بیشتر توجه می‌کشد. */
    if (window.DPPalette && DPPalette.HUE[hueKey]) {
      var C = DPPalette.HUE[hueKey];
      if (!C.neutral) {
        n += C.sat / 100;
        if (C.sat > 72 && C.light > 55) n += 0.4;   /* فلورسنتی */
      }
      /* پارچه‌ی چندرنگ خودش پرسروصداست */
      var cs = DPPalette.colorsOf(p);
      if (cs.length >= 3) n += 0.6;
      else if (cs.length === 2) n += 0.25;
    } else if (LOUD_COLORS[hueKey]) {
      n += LOUD_COLORS[hueKey];
    }

    if (p.fit === 'oversize') n += 0.5;
    return n;
  }

  function focusReport(items) {
    var loud = items.filter(function (x) { return x.loud >= 1; });
    if (loud.length === 0) {
      return { level: 'calm', text: 'تیپ کاملاً آرام — با یک اکسسوری رنگی جان می‌گیرد' };
    }
    if (loud.length === 1) {
      return { level: 'ideal', text: 'یک کانون توجه دارد؛ همان چیزی که استایلیست‌ها می‌گویند' };
    }
    return { level: 'busy', text: 'بیش از یک قطعه‌ی پرسروصدا — یکی را ساده‌تر بگیرید' };
  }

  /* ============================================================
     ۴. وزن پارچه و فصل — راهنمای واقعی خرید
     ============================================================ */
  var FABRIC_INFO = {
    cotton:    { name: 'نخ',        weight: 2, season: 'بهار و تابستان', care: 'شست‌وشوی آسان، ممکن است کمی آب برود' },
    linen:     { name: 'کتان',      weight: 1, season: 'تابستان',        care: 'خنک اما زود چروک می‌شود' },
    silk:      { name: 'ابریشم',    weight: 1, season: 'همه‌ی فصل‌ها',   care: 'خشک‌شویی — درخشش مجلسی' },
    wool:      { name: 'پشم',       weight: 4, season: 'پاییز و زمستان', care: 'گرم و ماندگار، شست‌وشوی ملایم' },
    cashmere:  { name: 'کشمیر',     weight: 4, season: 'زمستان',         care: 'سبک اما بسیار گرم — لوکس' },
    denim:     { name: 'جین',       weight: 3, season: 'همه‌ی فصل‌ها',   care: 'هرچه کمتر بشویید، بهتر می‌ماند' },
    leather:   { name: 'چرم',       weight: 4, season: 'پاییز و زمستان', care: 'با زمان قشنگ‌تر می‌شود' },
    polyester: { name: 'پلی‌استر',  weight: 2, season: 'همه‌ی فصل‌ها',   care: 'چروک نمی‌شود، اما کمتر نفس می‌کشد' },
    viscose:   { name: 'ویسکوز',    weight: 2, season: 'بهار',           care: 'افتادگی زیبا، حساس به آب داغ' },
    velvet:    { name: 'مخمل',      weight: 4, season: 'پاییز و زمستان', care: 'بافت مجلسی — با ساده‌ها ست کنید' },
    knit:      { name: 'بافت',      weight: 3, season: 'پاییز',          care: 'تخت خشک شود تا فرمش نرود' },
  };

  function fabricInfo(key) { return FABRIC_INFO[key] || null; }

  /* ============================================================
     ۵. تناسب فرم — واژه‌نامه‌ی واقعی
     ============================================================ */
  var FIT_INFO = {
    slim:     { name: 'جذب',      tip: 'با بالاتنه یا رویه‌ی گشاد بپوشید' },
    regular:  { name: 'استاندارد', tip: 'با همه‌چیز ست می‌شود — پایه‌ی کمد' },
    loose:    { name: 'گشاد',     tip: 'قطعه‌ی دیگر تیپ را جذب انتخاب کنید' },
    oversize: { name: 'اورسایز',  tip: 'حتماً با پایین‌تنه‌ی باریک — وگرنه هیکل گم می‌شود' },
  };

  function fitInfo(key) { return FIT_INFO[key] || null; }

  /* ============================================================
     ۶. راهنمای سایز — جدول واقعی ایران/اروپا
     ------------------------------------------------------------
     مبنا: استاندارد اندازه‌گیری پوشاک بزرگسال. اینها همان
     عددهایی است که روی برچسب برندهای معتبر می‌بینید.
     ============================================================ */
  var SIZE_TABLE = {
    XS:  { eu: '۳۴', chest: '۸۰–۸۴',  waist: '۶۲–۶۶'  },
    S:   { eu: '۳۶', chest: '۸۵–۸۹',  waist: '۶۷–۷۱'  },
    M:   { eu: '۳۸', chest: '۹۰–۹۴',  waist: '۷۲–۷۶'  },
    L:   { eu: '۴۰', chest: '۹۵–۹۹',  waist: '۷۷–۸۲'  },
    XL:  { eu: '۴۲', chest: '۱۰۰–۱۰۶', waist: '۸۳–۸۹'  },
    XXL: { eu: '۴۴', chest: '۱۰۷–۱۱۴', waist: '۹۰–۹۷'  },
  };

  function sizeInfo(s) {
    var k = String(s || '').toUpperCase().trim();
    return SIZE_TABLE[k] || null;
  }

  /* ============================================================
     ۷. ارزش کپسولی — «این قطعه چند تیپ می‌سازد؟»
     ------------------------------------------------------------
     مفهوم Capsule Wardrobe: یک قطعه‌ی خنثی و استاندارد با
     ده‌ها چیز ست می‌شود؛ یک قطعه‌ی پرطرح فقط با چند تا.
     این عدد به مشتری می‌گوید خریدش چقدر «به‌صرفه» است.
     ============================================================ */
  function versatility(p, hueKey, slot) {
    var n = 6;

    /* ---------- رنگ ----------
       دانشنامه خودش می‌داند کدام رنگ خنثی است — از «ذغالی»
       تا «بژ خاکستری». فهرست دستی همیشه ناقص می‌ماند. */
    if (window.DPPalette && DPPalette.HUE[hueKey]) {
      var C = DPPalette.HUE[hueKey];
      if (C.neutral) n += 5;
      else if (C.sat < 40) n += 2;        /* رنگ ملایم هم نسبتاً پایه است */
      else if (C.sat > 72) n -= 2;        /* رنگ فریادزن، کم‌کاربرد */
      else n -= 1;

      /* پارچه‌ی چندرنگ سخت‌تر ست می‌شود */
      var cs = DPPalette.colorsOf(p);
      if (cs.length >= 3) n -= 2;
    } else if (hueKey === 'black' || hueKey === 'white' || hueKey === 'gray'
      || hueKey === 'beige' || hueKey === 'navy' || hueKey === 'brown') {
      n += 5;
    } else {
      n -= 1;
    }

    /* ---------- طرح ---------- */
    if (window.DPPalette) {
      var pt = DPPalette.patternOf(p.pattern);
      if (pt.busy === 0) n += 3;
      else if (pt.busy === 1) n += 0;
      else if (pt.busy === 2) n -= 2;
      else n -= 3;
    } else {
      var pat = String(p.pattern || 'plain');
      if (pat === 'plain' || pat === 'none') n += 3; else n -= 2;
    }

    if (p.fit === 'regular') n += 2;
    if (p.fit === 'oversize') n -= 1;

    if (slot === 'bottom' || slot === 'top') n += 2;
    if (slot === 'shoes') n += 1;

    if (p.season === 'all') n += 2;

    n = Math.max(2, Math.min(18, n));

    var label = n >= 13 ? 'پایه‌ی کمد' : n >= 9 ? 'پرکاربرد' : n >= 6 ? 'کاربردی' : 'خاص‌پوش';
    return { count: n, label: label };
  }

  /* ============================================================
     ۸. نکته‌ی حرفه‌ای برای هر جایگاه — حرف یک استایلیست واقعی
     ============================================================ */
  var SLOT_TIP = {
    top: [
      'بالاتنه‌ی روشن‌تر از پایین‌تنه، قد را بلندتر نشان می‌دهد',
      'یقه‌ی باز، گردن را کشیده‌تر می‌کند',
      'اگر داخل شلوار می‌زنید، کمر را نشان دهید تا تناسب بهتر دیده شود',
    ],
    bottom: [
      'پایین‌تنه‌ی تیره‌تر، پایه‌ی مطمئن هر تیپ است',
      'قد شلوار تا استخوان قوزک، پا را بلندتر نشان می‌دهد',
      'با کفش هم‌رنگ شلوار، خط بدن پیوسته دیده می‌شود',
    ],
    outer: [
      'رویه باید کمی گشادتر باشد تا زیرش جا شود',
      'یک رویه‌ی خنثی، ده تیپ را نجات می‌دهد',
      'آستین رویه تا مچ — نه بیشتر',
    ],
    shoes: [
      'کفش تیپ را می‌بندد؛ کیفیتش بیش از همه دیده می‌شود',
      'رنگ کفش را با کمربند یا کیف هماهنگ کنید',
      'کفش نوک‌گرد راحت‌تر، نوک‌تیز رسمی‌تر',
    ],
    bag: [
      'کیف کوچک‌تر، تیپ را رسمی‌تر نشان می‌دهد',
      'کیف نقطه‌ی تأکید رنگی خوبی است',
    ],
    accessory: [
      'یک اکسسوری خوب، جای ده تای معمولی را می‌گیرد',
      'فلز اکسسوری‌ها را یکدست کنید — همه طلایی یا همه نقره‌ای',
    ],
    modest: [
      'شال هم‌خانواده با یکی از رنگ‌های تیپ، همه را به هم می‌دوزد',
      'شال ساده با لباس پرطرح، و برعکس',
    ],
    full: [
      'یک‌تکه ساده‌ترین راه تیپ کامل است — فقط کفش و کیف بخواهد',
      'کمربند روی یک‌تکه، فرم کمر می‌سازد',
    ],
  };

  function tipFor(slot, seed) {
    var list = SLOT_TIP[slot];
    if (!list || !list.length) return '';
    var n = String(seed || '').split('').reduce(function (a, c) {
      return a + c.charCodeAt(0);
    }, 0);
    return list[n % list.length];
  }

  /* ============================================================
     ۹. لحن حکم — چقدر مطمئنیم این ست خوب است؟
     ============================================================ */
  function verdictOf(score) {
    if (score >= 88) return { key: 'top',  name: 'ترکیب درجه‌یک', text: 'این ست را بدون تردید بپوشید' };
    if (score >= 78) return { key: 'good', name: 'ترکیب خوب',     text: 'هماهنگی مطمئن برای بیشتر مناسبت‌ها' };
    if (score >= 68) return { key: 'ok',   name: 'قابل قبول',     text: 'کار می‌کند؛ با یک اکسسوری بهتر هم می‌شود' };
    return { key: 'risk', name: 'جسورانه', text: 'ترکیب متفاوتی است — اگر اهل ریسک هستید' };
  }

  window.DPFashion = {
    OCCASION: OCCASION,
    occasionOf: occasionOf,
    shareOf: shareOf,
    balanceReport: balanceReport,
    loudnessOf: loudnessOf,
    focusReport: focusReport,
    fabricInfo: fabricInfo,
    fitInfo: fitInfo,
    sizeInfo: sizeInfo,
    versatility: versatility,
    tipFor: tipFor,
    verdictOf: verdictOf,
  };
})();
